#!/usr/bin/env python3
"""Scan assets/work/<project-slug>/ and write assets/work/manifest.js.

Drop a project's images into its folder, then run:  python3 scripts/build-images.py
  - a file named cover.* is the main image (hero reel, work grid, case-study hero, panels)
  - every other image becomes the case-study gallery, in filename order (01.jpg, 02.jpg ...)
  - no cover.* file? the first image (by name) is used as the cover
"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = os.path.join(ROOT, 'assets', 'work')
EXT = ('.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif')
slugs = re.findall(r"slug:'([^']+)'", open(os.path.join(ROOT, 'assets', 'data.js')).read())
out = {}
for slug in slugs:
    d = os.path.join(WORK, slug)
    files = sorted(f for f in os.listdir(d) if f.lower().endswith(EXT)) if os.path.isdir(d) else []
    if not files: continue
    cover = next((f for f in files if os.path.splitext(f)[0].lower() == 'cover'), files[0])
    # ?v=<modified time> so browsers re-download an image when it is replaced
    url = lambda f: f'assets/work/{slug}/{f}?v={int(os.path.getmtime(os.path.join(d, f)))}'
    out[slug] = {'cover': url(cover), 'gallery': [url(f) for f in files if f != cover]}
with open(os.path.join(WORK, 'manifest.js'), 'w') as f:
    f.write('// Generated by scripts/build-images.py. Do not edit by hand.\nconst IMAGES = ' + json.dumps(out, indent=2) + ';\n')
for s in slugs: print(f"{s:16} {'cover + ' + str(len(out[s]['gallery'])) + ' gallery' if s in out else 'placeholder'}")

# bump the manifest version in every page so browsers fetch the new list
import glob, time
v = int(time.time())
for page in glob.glob(os.path.join(ROOT, '*.html')):
    html = open(page).read()
    new = re.sub(r'assets/work/manifest\.js(\?v=\d+)?"', f'assets/work/manifest.js?v={v}"', html)
    if new != html: open(page, 'w').write(new)
